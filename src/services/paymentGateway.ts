import { CustomerInfo, Order, PaymentMethod } from '../types';

/**
 * SRI LANKA PAYMENT GATEWAY INTEGRATION SPECIFICATION
 * ----------------------------------------------------
 * This service handles payment orchestration for Sri Lankan e-commerce.
 * Primary supported gateways:
 * 1. PayHere (Sri Lanka's leading Central Bank CBSL-approved payment aggregator)
 * 2. Direct Bank Wire / Internet Banking Transfer (Commercial Bank / Sampath Bank)
 * 3. Cash on Delivery (Courier partners: Pronto / Domex / Prompt / Certis Lanka)
 */

export interface PayHereConfig {
  merchantId: string;
  isSandbox: boolean;
  returnUrl?: string;
  cancelUrl?: string;
  notifyUrl?: string;
}

export interface BankAccountDetails {
  bankName: string;
  accountName: string;
  accountNumber: string;
  branch: string;
  swiftCode?: string;
  whatsappConfirmation: string;
}

